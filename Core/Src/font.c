/* 8x16 bold font (for headers) — simplified: just 2x scale of 5x7 at draw time.
 * Provide glyph bitmaps only for uppercase + digits to keep flash down. */
const uint8_t Font8x16[95][16] = {0};  /* placeholder — headers use Font_DrawStr with 2x scale on 5x7 */

void Font_DrawChar(int16_t x, int16_t y, char ch, uint8_t font, uint8_t scale, Colour c)
{
    if (ch < 32 || ch > 126) return;
    uint8_t idx = (uint8_t)ch - 32;
    const uint8_t *glyph = (font == 0) ? Font5x7[idx] : NULL;
    int w = (font == 0) ? 5 : 0;
    int h = (font == 0) ? 7 : 0;
    if (!glyph) return;

    for (int row = 0; row < h; row++)
    {
        uint8_t line = glyph[row];
        for (int col = 0; col < w; col++)
        {
            if (line & (1U << col))
            {
                for (int sy = 0; sy < (int)scale; sy++)
                    for (int sx = 0; sx < (int)scale; sx++)
                        SSD1306_DrawPixel(x + col * (int)scale + sx, y + row * (int)scale + sy, c);
            }
        }
    }
}

void Font_DrawStr(int16_t x, int16_t y, const char *s, uint8_t font, uint8_t scale, Colour c)
{
    int16_t cx = x;
    while (*s)
    {
        Font_DrawChar(cx, y, *s, font, scale, c);
        cx += Font_CharWidth(font, scale);
        s++;
    }
}

int16_t Font_StrWidth(const char *s, uint8_t font, uint8_t scale)
{
    int16_t w = 0;
    while (*s++) w += Font_CharWidth(font, scale);
    return w;
}

int16_t Font_CharWidth(uint8_t font, uint8_t scale)
{
    return (font == 0) ? (int16_t)(6 * scale) : (int16_t)(9 * scale);
}

int16_t Font_CharHeight(uint8_t font, uint8_t scale)
{
    return (font == 0) ? (int16_t)(7 * scale) : (int16_t)(16 * scale);
}
