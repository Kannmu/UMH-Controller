def hdist():
    d = ELEM_XY[None, :, :] - MIC_XY[:, None, :]
    return np.hypot(d[..., 0], d[..., 1])          # [mic, ch]


def r_direct():
    return np.sqrt(hdist() ** 2 + SRC_Z ** 2)


def r_echo(table_mm=TABLE_MM):
    return np.sqrt(hdist() ** 2 + (2 * table_mm + SRC_Z) ** 2)


def ref_phase_bytes():
    import json
    with open("Utiles/cal_capture/eeprom_profile_backup_20260926_162735.json") as f:
        j = json.load(f)
    for key in ("phase_bytes", "phase_byte", "phase"):
        if key in j:
            v = np.array(j[key])
            return (v >> 8) if v.max() > 255 else v
    raise KeyError(list(j))
